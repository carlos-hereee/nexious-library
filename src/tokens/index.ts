// The design tokens as plain constants, for code that cannot read CSS custom properties.
//
// Why it exists: React Native (the client app shell) has no stylesheet cascade, so it cannot read
// var(--space-medium). This module carries the same values as vars/_tokens.scss and
// vars/_control.scss in a form native code can use: sizes and spacing as px numbers, colors and
// shadows as strings, and one color map per theme. It imports NOTHING, not React, not the DOM,
// not another file of this package, so it loads in any runtime and pulls nothing in with it.
//
// It is a mirror, never a source: the SCSS files are canonical (root CLAUDE.md rule 24), and
// __tests__/tokens/tokenParity.test.ts fails when a value here and its SCSS token disagree, or
// when the SCSS gains a token this file does not account for. Change the SCSS first, then this.
//
// Keys are the token names in camelCase with the group prefix dropped: --space-medium is
// space.medium, --text-2x-large is fontSize["2xLarge"], --main-brand-color is
// color.light.mainBrandColor.

